create table if not exists public.froginal_dogs_giveaway_entries (
  id bigint generated by default as identity primary key,
  wallet_address text not null,
  x_username text not null,
  quiz_answer text not null,
  created_at timestamptz not null default now()
);

create unique index if not exists froginal_dogs_giveaway_wallet_unique
  on public.froginal_dogs_giveaway_entries (wallet_address);

create unique index if not exists froginal_dogs_giveaway_x_username_unique
  on public.froginal_dogs_giveaway_entries (lower(x_username));

alter table public.froginal_dogs_giveaway_entries enable row level security;

revoke all on table public.froginal_dogs_giveaway_entries from anon, authenticated;
grant all on table public.froginal_dogs_giveaway_entries to service_role;
grant usage, select on sequence public.froginal_dogs_giveaway_entries_id_seq to service_role;
